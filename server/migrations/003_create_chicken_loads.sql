-- Chicken load records (live weight, dressed weight, wastage).
--
-- Key design notes:
--   • wastage_pct is a GENERATED ALWAYS AS STORED column — it is always
--     derived from live_weight_kg and dressed_weight_kg. It cannot be
--     independently edited. NULL when live_weight_kg = 0.
--   • load_number is human-readable (LD-00001) generated from a sequence.
--   • Correction loads reference their original via corrects_load_id.
--   • Historical corrections: insert new row with is_correction=TRUE;
--     original row is never edited.

BEGIN;

CREATE SEQUENCE IF NOT EXISTS chicken_load_seq START 1 INCREMENT 1;

CREATE TABLE chicken_loads (
  id                  UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
  load_number         TEXT        NOT NULL UNIQUE
                        DEFAULT 'LD-' || LPAD(nextval('chicken_load_seq')::TEXT, 5, '0'),
  load_date           DATE        NOT NULL,
  supplier_ref        TEXT,
  live_weight_kg      NUMERIC(10,3) NOT NULL
                        CHECK (live_weight_kg >= 0),
  dressed_weight_kg   NUMERIC(10,3) NOT NULL
                        CHECK (dressed_weight_kg >= 0),

  -- GENERATED ALWAYS AS: computed from live/dressed weights.
  -- Formula: ((live - dressed) / live) × 100, rounded to 4 decimal places.
  -- NULL when live_weight_kg = 0 (NULLIF prevents division by zero).
  -- This column CANNOT be set or updated directly.
  wastage_pct         NUMERIC(7,4) GENERATED ALWAYS AS (
                        ROUND(
                          ((live_weight_kg - dressed_weight_kg)
                            / NULLIF(live_weight_kg, 0)) * 100,
                          4
                        )
                      ) STORED,

  remaining_stock_kg  NUMERIC(10,3)
                        CHECK (remaining_stock_kg >= 0),
  notes               TEXT,
  is_correction       BOOLEAN     NOT NULL DEFAULT FALSE,
  corrects_load_id    UUID        REFERENCES chicken_loads(id) ON DELETE RESTRICT,
  created_by          UUID        NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  -- Dressed weight cannot exceed live weight
  CONSTRAINT chk_dressed_le_live
    CHECK (dressed_weight_kg <= live_weight_kg),

  -- A correction row must point to its original load
  CONSTRAINT chk_correction_needs_ref
    CHECK (is_correction = FALSE OR corrects_load_id IS NOT NULL)
);

COMMENT ON TABLE  chicken_loads IS 'Daily chicken load records. Corrections are new rows, not edits.';
COMMENT ON COLUMN chicken_loads.wastage_pct IS
  'Generated column: ((live-dressed)/live)*100. NULL when live_weight=0. Cannot be edited directly.';
COMMENT ON COLUMN chicken_loads.load_number IS 'Human-readable ID: LD-00001. Generated by sequence.';
COMMENT ON COLUMN chicken_loads.remaining_stock_kg IS 'Manually observed remaining stock. Never auto-calculated.';

COMMIT;
