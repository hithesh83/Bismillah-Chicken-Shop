-- Sales header and line items.
--
-- Key design notes:
--   • status lifecycle: draft → confirmed → voided (never backwards)
--   • sale_number is human-readable (SL-000001) from a sequence.
--   • total_amount is a snapshot set by the application within a transaction,
--     then OVERWRITTEN by the confirm trigger with the DB-computed sum.
--   • sale_items are immutable after the parent sale is confirmed/voided.
--   • Triggers are created in migration 011.
--
-- Rounding policy (authoritative):
--   line_total   = ROUND(quantity_kg × rate_per_kg, 2)   ← per line
--   total_amount = SUM(line_total)                        ← exact sum, no re-rounding
--   line_total = 0 is rejected by CHECK (line_total > 0)
--
-- Sale types:
--   walkin        — no party; cash only; not tracked on party ledger
--   party_cash    — party recorded; payment collected at sale; nets to zero on ledger
--   party_credit  — party recorded; payment expected later; tracked on ledger

BEGIN;

CREATE SEQUENCE IF NOT EXISTS sale_seq START 1 INCREMENT 1;

CREATE TABLE sales (
  id               UUID          PRIMARY KEY DEFAULT gen_random_uuid(),
  sale_number      TEXT          NOT NULL UNIQUE
                     DEFAULT 'SL-' || LPAD(nextval('sale_seq')::TEXT, 6, '0'),
  status           TEXT          NOT NULL DEFAULT 'draft'
                     CHECK (status IN ('draft', 'confirmed', 'voided')),
  sale_timestamp   TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
  -- Business date in IST, used for daily reports
  -- Application sets: (NOW() AT TIME ZONE 'Asia/Kolkata')::DATE
  sale_date        DATE          NOT NULL,
  party_id         UUID          REFERENCES parties(id) ON DELETE RESTRICT,
  sale_type        TEXT          NOT NULL
                     CHECK (sale_type IN ('walkin', 'party_cash', 'party_credit')),
  total_amount     NUMERIC(12,2) NOT NULL DEFAULT 0
                     CHECK (total_amount >= 0),
  notes            TEXT,
  created_by       UUID          NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  created_at       TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
  updated_at       TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
  voided_at        TIMESTAMPTZ,
  voided_by        UUID          REFERENCES users(id) ON DELETE RESTRICT,
  void_reason      TEXT,
  is_correction    BOOLEAN       NOT NULL DEFAULT FALSE,
  corrects_sale_id UUID          REFERENCES sales(id) ON DELETE RESTRICT,

  -- Credit sales must have a party
  CONSTRAINT chk_credit_sale_needs_party
    CHECK (sale_type != 'party_credit' OR party_id IS NOT NULL),

  -- Void fields must be consistent
  CONSTRAINT chk_sale_void_fields
    CHECK ((voided_at IS NULL) = (voided_by IS NULL)),

  -- Status must match void state
  CONSTRAINT chk_voided_implies_status
    CHECK (voided_at IS NULL OR status = 'voided'),

  -- A correction must reference the original sale
  CONSTRAINT chk_correction_needs_ref
    CHECK (is_correction = FALSE OR corrects_sale_id IS NOT NULL)
);

CREATE TABLE sale_items (
  id          UUID          PRIMARY KEY DEFAULT gen_random_uuid(),
  sale_id     UUID          NOT NULL REFERENCES sales(id) ON DELETE RESTRICT,
  product_id  UUID          NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
  quantity_kg NUMERIC(10,3) NOT NULL CHECK (quantity_kg > 0),
  rate_per_kg NUMERIC(10,2) NOT NULL CHECK (rate_per_kg > 0),
  -- line_total = ROUND(quantity_kg × rate_per_kg, 2)
  -- Must be > 0; zero-total lines are rejected (catches rounding-to-zero edge case)
  line_total  NUMERIC(12,2) NOT NULL CHECK (line_total > 0),
  created_at  TIMESTAMPTZ   NOT NULL DEFAULT NOW()
  -- No updated_at: sale_items are immutable after insert.
  -- Correction = void original sale, create new sale with new items.
);

COMMENT ON TABLE  sales                IS 'Sale headers. status: draft → confirmed → voided.';
COMMENT ON COLUMN sales.sale_number    IS 'Human-readable ID: SL-000001. Generated by sequence.';
COMMENT ON COLUMN sales.status         IS 'draft=building | confirmed=locked | voided=cancelled';
COMMENT ON COLUMN sales.total_amount   IS
  'Snapshot set by application; overwritten by confirm trigger with SUM(sale_items.line_total).';
COMMENT ON COLUMN sales.sale_date      IS 'Business date in IST. Set by application: (NOW() AT TIME ZONE Asia/Kolkata)::DATE';
COMMENT ON TABLE  sale_items           IS 'Line items. Immutable after parent sale is confirmed.';
COMMENT ON COLUMN sale_items.line_total IS 'ROUND(quantity_kg × rate_per_kg, 2). Stored at insert time.';

COMMIT;
