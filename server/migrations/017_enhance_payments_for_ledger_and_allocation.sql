-- Add human-readable payment number sequence and idempotency key to payments.
--
-- Enables:
--   1. Standardized receipt numbering: PMT-000001, PMT-000002...
--   2. Duplicate submission protection via idempotency_key
--   3. Fast lookup by payment_number

BEGIN;

CREATE SEQUENCE IF NOT EXISTS seq_payment_number START 1;

ALTER TABLE payments
  ADD COLUMN IF NOT EXISTS payment_number TEXT UNIQUE
    DEFAULT ('PMT-' || LPAD(nextval('seq_payment_number')::TEXT, 6, '0')),
  ADD COLUMN IF NOT EXISTS idempotency_key TEXT UNIQUE;

-- Backfill any existing payments with sequence numbers
UPDATE payments
  SET payment_number = ('PMT-' || LPAD(nextval('seq_payment_number')::TEXT, 6, '0'))
  WHERE payment_number IS NULL;

CREATE INDEX IF NOT EXISTS idx_payments_number
  ON payments(payment_number);

CREATE INDEX IF NOT EXISTS idx_payments_idempotency_key
  ON payments(idempotency_key)
  WHERE idempotency_key IS NOT NULL;

COMMENT ON COLUMN payments.payment_number IS 'Human-readable receipt ID: PMT-000001. Generated by sequence.';
COMMENT ON COLUMN payments.idempotency_key IS 'Unique client request token to prevent double payments.';

COMMIT;
